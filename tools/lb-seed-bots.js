#!/usr/bin/env node
// СТАРТОВЫЕ БОТЫ ТАБЛИЦЫ ЛИДЕРОВ (слово владельца 2026-08-10: «заполни
// лидерборд 15 игроками для примера, пусть это будут начальные боты»).
//
// ⚠️⚠️ БОТЫ ЗАВОДЯТСЯ ПУБЛИЧНЫМ API, А НЕ ЗАПИСЬЮ В БАЗУ. Причина не в
// отсутствии доступа (его действительно нет), а в том, что так честнее:
// строка появляется ровно тем путём, которым её создаёт живой игрок (TOFU —
// первая отправка несёт ключ). Значит боты не могут «уметь» того, чего не
// умеет игрок, и никакой особой ветки в сервере под них не заводится.
//
// ⚠️ ID С ПРЕФИКСОМ `bot-` — ЧТОБЫ ИХ МОЖНО БЫЛО НАЙТИ И УБРАТЬ. Игроку id
// не виден нигде (на экране только имя, аватар и счёт), а нам он нужен как
// единственный признак: «это посев, а не человек».
//
// ⚠️ ЛЕСЕНКА СЧЁТА НАЧИНАЕТСЯ НИЗКО НАМЕРЕННО. Уровень даёт ~600-800 очков в
// деноминации кошелька, поэтому ПЕРВАЯ ЖЕ победа обязана поднять новичка над
// парой ботов. Посев из сильных игроков читался бы как «мне сюда не попасть».
// ⚠️⚠️ НЕДОРАБОТКА ПЕРВОГО ПРОГОНА, ЗАПИСЫВАЮ ЧЕСТНО: скрипт НЕ СОХРАНИЛ
// ключи `k` заведённых ботов. Следствие — их строки больше нельзя ни
// обновить, ни удалить ПРОТОКОЛОМ (`/v1/del` требует подпись тем же ключом);
// остаётся `/admin/hide` или прямая правка базы. Ниже ключи пишутся в файл
// рядом; id первой партии сохранены в `lb-seed-bots.ids.txt`.
const fs = require('fs');
const crypto = require('crypto');

const BASE = process.argv[2] || 'https://lb.blendo.monster';
const ИМЕНА = ['Otter','Falcon','Lynx','Heron','Marten','Puffin','Ibex','Quokka',
               'Serval','Narwhal','Kestrel','Wombat','Caracal','Stoat','Osprey'];
const АВАТАРЫ = [4, 11, 19, 27, 33, 7, 41, 15, 22, 36, 48, 2, 29, 44, 9];
const СЧЁТ    = [240, 480, 760, 1120, 1560, 2080, 2700, 3450, 4300,
                 5300, 6500, 7900, 9600, 11800, 14500];

const hex = (n) => crypto.randomBytes(n).toString('hex');
const подпись = (kHex, msg) =>
  crypto.createHmac('sha256', Buffer.from(kHex, 'hex')).update(msg, 'utf8').digest('hex');

(async () => {
  const итог = [];
  for (let i = 0; i < ИМЕНА.length; i++) {
    const id = 'bot-' + hex(6), k = hex(32);
    const s = СЧЁТ[i], q = 1, t = Math.floor(Date.now() / 1000);
    const payload = { id, k, n: ИМЕНА[i], a: АВАТАРЫ[i], s, q, t,
                      sig: подпись(k, id + '.' + s + '.' + q + '.' + t) };
    let ответ = null, код = 0;
    try {
      const r = await fetch(BASE + '/v1/score',
        { method: 'POST', headers: { 'content-type': 'text/plain' }, body: JSON.stringify(payload) });
      код = r.status; ответ = await r.json().catch(() => null);
    } catch (e) { ответ = { err: String(e && e.message || e) }; }
    // ⚠️ «Тело разобралось» ≠ успех: у нас мягкая деградация, и отказ живёт
    // ПОЛЕМ `err`, а не кодом ответа. Читаем именно его.
    const ок = !!(ответ && ответ.ok && !ответ.err);
    итог.push({ имя: ИМЕНА[i], счёт: s, id, k, код, ок, err: ответ && ответ.err });
    console.log((ок ? '  ✅' : '  ⛔') + ' ' + ИМЕНА[i].padEnd(9) + String(s).padStart(6) +
                '  ' + id + (ок ? '' : '  ' + код + ' ' + JSON.stringify(ответ)));
    await new Promise(r => setTimeout(r, 120));   // не долбим воркер залпом
  }
  // КЛЮЧИ НА ДИСК СРАЗУ — без них партия становится неудаляемой (см. шапку).
  fs.writeFileSync(__dirname + '/lb-seed-bots.keys.json', JSON.stringify(итог, null, 1));
  console.log('\nключи записаны: tools/lb-seed-bots.keys.json (НЕ коммитить)');
  const хорошо = итог.filter(x => x.ок).length;
  console.log('\nЗАВЕДЕНО: ' + хорошо + ' из ' + итог.length);
  if (хорошо !== итог.length) process.exitCode = 1;
})();
