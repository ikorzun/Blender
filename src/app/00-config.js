// открыть панель на живом GitHub Pages, не пересобирая игру.
// ⚠️ 'mixer_dev' = '0' ПРИНУДИТЕЛЬНО ВЫКЛЮЧАЕТ — иначе боевое поведение
// невозможно проверить тестом: он всегда ходит по file://.
const DEV = (function(){
  try {
    if (localStorage.getItem('mixer_dev') === '0') return false;
    if (localStorage.getItem('mixer_dev') === '1') return true;
    if (/[?&]dev=1/.test(location.search)) return true;
    if (location.protocol === 'file:') return true;
    const h = location.hostname;
    return h === 'localhost' || h === '127.0.0.1' || h === '';
  } catch(e){ return false; }
})();
// класс на <html> — им CSS показывает вход в отладку (иначе он скрыт всегда)
try { if (DEV) document.documentElement.classList.add('dev'); } catch(e){}

