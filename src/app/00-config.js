// открывающий игру ПО HTTP и без этого признака, — он будет писать в боевую
// базу, и молча.
// ⚠️ И вторая, названная заранее цена: гейт НЕ закрывает РУЧНЫЕ прогоны
// направлений на их превью-портах (8779/8781). Человек, доигравший там
// уровень, заводит настоящую строку. Это осознанный размен — иначе владелец
// снова остался бы без своей строки, — лечится ссылкой `?lb=1`.
const LB_NOSEND = (function () {
  try {
    if (typeof location !== 'undefined' && location.protocol === 'file:') return true;
    return !!(typeof navigator !== 'undefined' && navigator.webdriver);
  } catch (e) { return true; }
})();
