// верен с запасом 1.36×. ⚠️ ПРИ СЛЕДУЮЩЕЙ СМЕНЕ ПАРТИИ МОДЕЛЕЙ ПЕРЕМЕРИТЬ:
// число выведено из формы предметов, а не из физики вообще.
// ⚠️ НА ЛЕТЯЩЕЙ КУЧЕ ЭТИ ЧИСЛА ДРУГИЕ (p95 0.13, max 0.28) и порогом НЕ
